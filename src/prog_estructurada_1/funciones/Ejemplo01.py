#Ejemplo de funcion y procedimiento 

#Funcion porque devuelve un resultado
def sumar(a,b):
    resultado = a+b
    return resultado

#Ejemplo de procedimiento 
def mostrar_suma(a,b):
    print("La suma es:",a+b)


#Uso de la funcion y el procedimiento 
valor = sumar(10,20)
print("El valor de la suma es:",valor)

mostrar_suma(15,25)